<?php

declare(strict_types=1);

namespace Nowo\AuthKitBundle\EventSubscriber;

use Nowo\AuthKitBundle\Enum\LocaleInPathMode;
use Nowo\AuthKitBundle\Enum\UnlocalizedLocaleMode;
use Nowo\AuthKitBundle\Profile\RequestProfileResolver;
use Nowo\AuthKitBundle\Routing\AuthKitRouteLoader;
use Symfony\Component\EventDispatcher\EventSubscriberInterface;
use Symfony\Component\HttpFoundation\RedirectResponse;
use Symfony\Component\HttpFoundation\Response;
use Symfony\Component\HttpKernel\Event\RequestEvent;
use Symfony\Component\HttpKernel\KernelEvents;
use Symfony\Component\Routing\Exception\ExceptionInterface as RoutingException;
use Symfony\Component\Routing\Generator\UrlGeneratorInterface;

use function in_array;
use function is_array;
use function is_bool;
use function is_string;
use function str_contains;
use function str_starts_with;

/**
 * Opt-in (locale.localized_logout_redirect, 1.32.2): with locale.in_path "both" and unlocalized "serve" the firewall
 * logout.path is the bare twin ("nowo_auth_kit_logout_unlocalized"), which matches "/logout" only. This listener
 * sends "/{_locale}/logout" to that bare URL so the firewall intercepts both.
 *
 * Only the logout routes of the AuthKit profiles are redirected; the target is generated by the router from the
 * bare route name (same-origin path, never taken from the request) and keeps the query string (the CSRF token).
 * GET/HEAD answer 302; other methods 307 so a POST sign-out keeps its body.
 */
final readonly class LocalizedLogoutRedirectSubscriber implements EventSubscriberInterface
{
    /** After the router (32) and the locale listeners (16/15/14); before the firewall (8). */
    public const PRIORITY = 9;

    private bool $active;

    /** @var list<string> localized logout route names of every profile */
    private array $logoutRoutes;

    /**
     * @param array<string, array<string, mixed>> $profiles
     */
    public function __construct(
        private UrlGeneratorInterface $urlGenerator,
        array $profiles,
        string|bool $localeInPath,
        string $unlocalizedMode,
        bool $enabled,
        private string $unlocalizedRouteSuffix = AuthKitRouteLoader::UNLOCALIZED_ROUTE_SUFFIX,
    ) {
        $inPath = is_bool($localeInPath)
            ? ($localeInPath ? LocaleInPathMode::Always : LocaleInPathMode::Never)
            : LocaleInPathMode::from($localeInPath);

        $this->active = $enabled
            && $inPath === LocaleInPathMode::Both
            && UnlocalizedLocaleMode::from($unlocalizedMode) === UnlocalizedLocaleMode::Serve;

        $routes = [];
        foreach ($profiles as $profile) {
            $name = $profile['routes']['logout']['name'] ?? null;
            if (is_string($name) && $name !== '' && !in_array($name, $routes, true)) {
                $routes[] = $name;
            }
        }
        $this->logoutRoutes = $routes;
    }

    /**
     * @return array<string, list<array{0: string, 1: int}>>
     */
    public static function getSubscribedEvents(): array
    {
        return [
            KernelEvents::REQUEST => [['onKernelRequest', self::PRIORITY]],
        ];
    }

    public function onKernelRequest(RequestEvent $event): void
    {
        if (!$this->active || !$event->isMainRequest()) {
            return;
        }

        $request = $event->getRequest();
        $route   = $request->attributes->get('_route');
        if (!is_string($route) || !in_array($route, $this->logoutRoutes, true)) {
            return;
        }

        $parameters = $request->attributes->get('_route_params', []);
        if (!is_array($parameters)) {
            $parameters = [];
        }
        unset($parameters['_locale'], $parameters[RequestProfileResolver::REQUEST_ATTRIBUTE]);

        try {
            $url = $this->urlGenerator->generate($route . $this->unlocalizedRouteSuffix, $parameters, UrlGeneratorInterface::ABSOLUTE_PATH);
        } catch (RoutingException) {
            return;
        }

        // SEC-004 L3: only same-origin, path-absolute targets (never `//host`, `/\host` or a scheme).
        if (!str_starts_with($url, '/') || str_starts_with($url, '//') || str_starts_with($url, '/\\')) {
            return;
        }

        $queryString = $request->getQueryString();
        if ($queryString !== null && $queryString !== '') {
            $url .= (str_contains($url, '?') ? '&' : '?') . $queryString;
        }

        $status = in_array($request->getMethod(), ['GET', 'HEAD'], true) ? Response::HTTP_FOUND : Response::HTTP_TEMPORARY_REDIRECT;
        $event->setResponse(new RedirectResponse($url, $status));
    }
}
